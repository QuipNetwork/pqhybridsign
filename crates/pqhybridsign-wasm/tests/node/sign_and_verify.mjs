// Signs and verifies for every suite this binding exposes (H1-H4),
// confirms H5/H6 are refused with an explanatory error rather than
// silently mishandled, and confirms a tampered message and a
// wrong-suite signature both fail verification. Also exercises
// verifyStateful/verifyStateless,
// verifyWithStoredPublicKeyStateful/verifyWithStoredPublicKeyStateless and
// storedPublicKeyLen, the H5/H6 verify entry points this binding exposes
// (see lib.rs for why verification is safe where signing is not). Run
// against a `nodejs`-target build assembled by ../../scripts/build-npm.sh:
//
//   ../../scripts/build-npm.sh
//   node tests/node/sign_and_verify.mjs
//
// Exits nonzero on any failure, so this is safe to wire into
// continuous integration directly.

import assert from "node:assert/strict";
import { Buffer } from "node:buffer";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as pqhs from "../../npm/node/pqhybridsign_wasm.js";

const SUITES = ["H1", "H2", "H3", "H4"];
const STATEFUL_SUITES = ["H5", "H6"];
const MSG = new TextEncoder().encode("the message the node test signs");
const MSG2 = new TextEncoder().encode("a second, different message");
const CTX = new TextEncoder().encode("node-sign-and-verify-test");

function seed(byte) {
    return new Uint8Array(32).fill(byte);
}

// A synchronous in-memory LeafJournal, the shape signStateful drives. It is
// NOT durable -- a real integrator persists commit() and bindKey() to storage
// that survives a restart -- but within a session it exercises the identity
// binding and the lockstep counter check exactly as a durable journal would.
// Mirrors the native MemoryJournal in
// ../generate_verify_with_stored_public_key_fixture.rs.
class MemoryLeafJournal {
    #next = 0;
    #bound = null;
    commit(leaf) {
        // next_leaf() must report leaf + 1 after a commit(leaf); the abi only
        // ever commits the leaf it just read, so this stays monotone.
        if (leaf + 1 > this.#next) this.#next = leaf + 1;
    }
    nextLeaf() {
        return this.#next;
    }
    boundKey() {
        return this.#bound === null ? null : this.#bound.slice();
    }
    bindKey(identity) {
        this.#bound = identity.slice();
    }
}

// A synchronous in-memory StatelessBudgetStore, the counterpart of
// MemoryLeafJournal for signStateless. Not durable, on the same terms.
class MemoryStatelessBudget {
    #counts = new Map();
    static #hex(bytes) {
        let s = "";
        for (const b of bytes) s += b.toString(16).padStart(2, "0");
        return s;
    }
    consumed(key) {
        const v = this.#counts.get(MemoryStatelessBudget.#hex(key));
        return v === undefined ? null : v;
    }
    record(key, count) {
        this.#counts.set(MemoryStatelessBudget.#hex(key), count);
    }
}

let failures = 0;

function check(name, fn) {
    try {
        fn();
        console.log(`ok - ${name}`);
    } catch (err) {
        failures += 1;
        console.error(`not ok - ${name}`);
        console.error(err);
    }
}

// Fixture for verifyWithStoredPublicKey/storedPublicKeyLen, generated by
// ../generate_verify_with_stored_public_key_fixture.rs against Suite.H5.
// `stored` is the small form a verifier installs; `bundle` is the
// signer-supplied commitment bundle for the same key, over the stateless
// path (`PathSelector` 0x02); `statefulSig` is a second signature over the
// same message from the stateful path (0x01, one leaf spent); `attackerBundle`
// is the bundle of an unrelated key that signs the same message. Loaded and
// profile-checked before any other check runs: a profile mismatch must fail
// with a message naming the cause, not as an opaque `true !== false` deep
// inside an unrelated assertion.
const fixturePath = fileURLToPath(
    new URL("./verify_with_stored_public_key.fixture.json", import.meta.url),
);
const fixture = JSON.parse(readFileSync(fixturePath, "utf8"));
const hex = (s) => Uint8Array.from(Buffer.from(s, "hex"));
const STORED = hex(fixture.stored);
const BUNDLE = hex(fixture.bundle);
const ATTACKER_BUNDLE = hex(fixture.attackerBundle);
const STORED_MSG = hex(fixture.msg);
const STORED_CTX = hex(fixture.ctx);
const STORED_SIG = hex(fixture.sig);
const STORED_STATEFUL_SIG = hex(fixture.statefulSig);

check("verify_with_stored_public_key fixture matches the build's SHRINCS profile", () => {
    assert.equal(
        pqhs.profileName(),
        fixture.profile,
        `fixture was generated against "${fixture.profile}" but this build links ` +
            `"${pqhs.profileName()}"; regenerate the fixture with ` +
            "generate_verify_with_stored_public_key_fixture before trusting any " +
            "check that uses it",
    );
});

check("profileName reports a shrincs profile", () => {
    assert.match(pqhs.profileName(), /^shrincs-/);
});

for (const [i, suite] of SUITES.entries()) {
    check(`${suite}: keygen, sign, verify round-trip`, () => {
        const { secretKey, publicKey } = pqhs.keygenFromSeed(suite, seed(i + 1));
        assert.equal(secretKey.length, pqhs.secretKeyLen(suite));
        assert.equal(publicKey.length, pqhs.publicKeyLen(suite));

        const sig = pqhs.sign(suite, secretKey, MSG, CTX);
        assert.ok(sig.length <= pqhs.signatureLen(suite));
        assert.equal(pqhs.verify(suite, publicKey, MSG, CTX, sig), true);
    });

    check(`${suite}: deterministic signing is repeatable`, () => {
        const { secretKey, publicKey } = pqhs.keygenFromSeed(suite, seed(i + 1));
        const nonce = new TextEncoder().encode("fixed-nonce");
        const sigA = pqhs.signDeterministic(suite, secretKey, MSG, CTX, nonce);
        const sigB = pqhs.signDeterministic(suite, secretKey, MSG, CTX, nonce);
        assert.deepEqual(sigA, sigB);
        assert.equal(pqhs.verify(suite, publicKey, MSG, CTX, sigA), true);
    });

    check(`${suite}: a tampered message fails to verify`, () => {
        const { secretKey, publicKey } = pqhs.keygenFromSeed(suite, seed(i + 1));
        const sig = pqhs.sign(suite, secretKey, MSG, CTX);
        const tampered = new TextEncoder().encode("a different message entirely");
        assert.equal(pqhs.verify(suite, publicKey, tampered, CTX, sig), false);
    });
}

check("a signature from one suite fails to verify under another", () => {
    const { secretKey: h1sk, publicKey: h1pk } = pqhs.keygenFromSeed("H1", seed(1));
    const sig = pqhs.sign("H1", h1sk, MSG, CTX);
    const { publicKey: h3pk } = pqhs.keygenFromSeed("H3", seed(1));
    assert.equal(pqhs.verify("H1", h1pk, MSG, CTX, sig), true);
    assert.equal(pqhs.verify("H3", h3pk, MSG, CTX, sig), false);
});

for (const suite of ["H5", "H6"]) {
    check(`${suite}: the stateless entry points are refused and name the stateful ones`, () => {
        // keygenFromSeed/sign/signDeterministic are the stateless path and
        // must never silently spend a one-time leaf; each rejects H5/H6 with
        // a message that points at keygenStatefulFromSeed/signStateful.
        for (const call of [
            () => pqhs.keygenFromSeed(suite, seed(1)),
            () => pqhs.sign(suite, new Uint8Array(32), MSG, CTX),
            () => pqhs.signDeterministic(suite, new Uint8Array(32), MSG, CTX, seed(9)),
        ]) {
            assert.throws(call, (err) => {
                assert.ok(err instanceof Error);
                assert.match(err.message, /stateful suite/);
                assert.match(err.message, /signStateful/);
                return true;
            });
        }
    });

    check(`${suite}: the length accessors are total, like the C and Python bindings`, () => {
        assert.ok(pqhs.publicKeyLen(suite) > 0);
        assert.ok(pqhs.secretKeyLen(suite) > 0);
        assert.ok(pqhs.signatureLen(suite) > 0);
        assert.ok(pqhs.storedPublicKeyLen(suite) > 0);
    });
}

check("an unknown suite name is refused", () => {
    assert.throws(() => pqhs.keygenFromSeed("H7", seed(1)));
});

const MALFORMED = [
    new Uint8Array(0),
    new Uint8Array(1),
    new Uint8Array(4096),
];

for (const suite of SUITES) {
    check(`${suite}: verify returns false and does not throw for malformed lengths`, () => {
        const { secretKey, publicKey } = pqhs.keygenFromSeed(suite, seed(1));
        const sig = pqhs.sign(suite, secretKey, MSG, CTX);
        for (const bad of MALFORMED) {
            assert.equal(pqhs.verify(suite, publicKey, MSG, CTX, bad), false);
            assert.equal(pqhs.verify(suite, bad, MSG, CTX, sig), false);
        }
    });
}

check("storedPublicKeyLen(H5) matches the fixture's stored form", () => {
    assert.equal(pqhs.storedPublicKeyLen("H5"), fixture.storedLen);
    assert.equal(STORED.length, fixture.storedLen);
});

check("storedPublicKeyLen is total over H1-H4, agreeing with publicKeyLen", () => {
    // Unlike verifyWithStoredPublicKey, storedPublicKeyLen is a plain length
    // accessor over public data and must not throw for the four suites this
    // binding actually signs and verifies with -- the stored and verify
    // forms are the same bytes for H1-H4, so this equals publicKeyLen. This
    // is the same contract the C (`pqhs_stored_public_key_len`) and Python
    // (`stored_public_key_len`) bindings already give those four suites.
    for (const suite of SUITES) {
        assert.equal(pqhs.storedPublicKeyLen(suite), pqhs.publicKeyLen(suite));
    }
});

check("verifyWithStoredPublicKeyStateful and verifyWithStoredPublicKeyStateless are refused for H1-H4", () => {
    // Both stay H5/H6-only, matching the C
    // `PQHS_ERR_WRONG_ENTRY_POINT_FOR_SUITE` and Python
    // `WrongEntryPointForSuiteError`: this is semantically a stateful
    // operation, unlike storedPublicKeyLen above.
    for (const suite of SUITES) {
        assert.throws(() =>
            pqhs.verifyWithStoredPublicKeyStateful(suite, STORED, BUNDLE, STORED_MSG, STORED_CTX, STORED_STATEFUL_SIG),
        );
        assert.throws(() =>
            pqhs.verifyWithStoredPublicKeyStateless(suite, STORED, BUNDLE, STORED_MSG, STORED_CTX, STORED_SIG),
        );
    }
});

check("verifyWithStoredPublicKeyStateless accepts the bundle the stored key names", () => {
    assert.equal(
        pqhs.verifyWithStoredPublicKeyStateless(
            "H5",
            STORED,
            BUNDLE,
            STORED_MSG,
            STORED_CTX,
            STORED_SIG,
        ),
        true,
    );
});

check("verifyWithStoredPublicKeyStateful accepts the stateful-path signature", () => {
    assert.equal(
        pqhs.verifyWithStoredPublicKeyStateful(
            "H5",
            STORED,
            BUNDLE,
            STORED_MSG,
            STORED_CTX,
            STORED_STATEFUL_SIG,
        ),
        true,
    );
});

check("each stored-public-key entry point refuses the other path's signature by selector", () => {
    // STORED_SIG carries PathSelector 0x02 (stateless), STORED_STATEFUL_SIG
    // carries 0x01 (stateful, one leaf spent). Each entry point refuses the
    // signature that does not name its own path, before either component
    // signature is checked.
    assert.equal(
        pqhs.verifyWithStoredPublicKeyStateful(
            "H5",
            STORED,
            BUNDLE,
            STORED_MSG,
            STORED_CTX,
            STORED_SIG,
        ),
        false,
    );
    assert.equal(
        pqhs.verifyWithStoredPublicKeyStateless(
            "H5",
            STORED,
            BUNDLE,
            STORED_MSG,
            STORED_CTX,
            STORED_STATEFUL_SIG,
        ),
        false,
    );
});

check("verifyWithStoredPublicKeyStateless refuses a bundle the stored key does not name", () => {
    // The attacker's own bundle verifies the same signature's message and
    // context perfectly well as a self-consistent key; what it fails is
    // the binding to the *stored* commitment, which is what this entry
    // point exists to check.
    assert.equal(
        pqhs.verifyWithStoredPublicKeyStateless(
            "H5",
            STORED,
            ATTACKER_BUNDLE,
            STORED_MSG,
            STORED_CTX,
            STORED_SIG,
        ),
        false,
    );
});

check("verifyWithStoredPublicKeyStateless returns false and does not throw for malformed lengths", () => {
    for (const bad of MALFORMED) {
        assert.equal(
            pqhs.verifyWithStoredPublicKeyStateless("H5", bad, BUNDLE, STORED_MSG, STORED_CTX, STORED_SIG),
            false,
        );
        assert.equal(
            pqhs.verifyWithStoredPublicKeyStateless("H5", STORED, bad, STORED_MSG, STORED_CTX, STORED_SIG),
            false,
        );
    }
});

// ---- Stateful signing (H5, H6) through the functional journal API ----

for (const [i, suite] of STATEFUL_SUITES.entries()) {
    check(`${suite}: keygenStatefulFromSeed -> adoptKey -> signStateful -> verify`, () => {
        const { secretKey, publicKey } = pqhs.keygenStatefulFromSeed(suite, seed(0x50 + i), 4);
        assert.equal(secretKey.length, pqhs.secretKeyLen(suite));
        assert.equal(publicKey.length, pqhs.publicKeyLen(suite));

        const journal = new MemoryLeafJournal();
        pqhs.adoptKey(journal, pqhs.keyIdentity(suite, publicKey));

        const { signature, nextSecretKey } = pqhs.signStateful(suite, secretKey, journal, MSG, CTX);
        assert.ok(signature.length <= pqhs.signatureLen(suite));
        assert.equal(nextSecretKey.length, pqhs.secretKeyLen(suite));
        // The returned blob is advanced past the leaf just spent, and the
        // journal moved with it.
        assert.notDeepEqual(nextSecretKey, secretKey);
        assert.equal(journal.nextLeaf(), 1);
        assert.equal(pqhs.verify(suite, publicKey, MSG, CTX, signature), true);
        // A tampered message must not verify against a real stateful signature.
        assert.equal(pqhs.verify(suite, publicKey, MSG2, CTX, signature), false);
        // The path-explicit entry points agree with plain `verify`: a
        // stateful-path signature verifies under verifyStateful and is
        // refused by verifyStateless.
        assert.equal(pqhs.verifyStateful(suite, publicKey, MSG, CTX, signature), true);
        assert.equal(pqhs.verifyStateless(suite, publicKey, MSG, CTX, signature), false);
    });

    check(`${suite}: keyIdentity and keyIdentityFromSecretKey name the same key`, () => {
        const { secretKey, publicKey } = pqhs.keygenStatefulFromSeed(suite, seed(0x60 + i), 4);
        assert.deepEqual(
            pqhs.keyIdentity(suite, publicKey),
            pqhs.keyIdentityFromSecretKey(suite, secretKey),
        );
    });

    check(`${suite}: reusing a stale blob is refused, never a reissued leaf`, () => {
        const { secretKey, publicKey } = pqhs.keygenStatefulFromSeed(suite, seed(0x70 + i), 4);
        const journal = new MemoryLeafJournal();
        pqhs.adoptKey(journal, pqhs.keyIdentity(suite, publicKey));

        // First signature spends leaf 0 and advances the journal to 1.
        const first = pqhs.signStateful(suite, secretKey, journal, MSG, CTX);
        assert.equal(journal.nextLeaf(), 1);

        // Reusing the ORIGINAL blob (still leaf 0) against the now-advanced
        // journal is the stale-blob hazard. The lockstep check refuses it
        // (CountersDiverged) rather than reissuing leaf 0 under a new message.
        assert.throws(
            () => pqhs.signStateful(suite, secretKey, journal, MSG2, CTX),
            (err) => {
                assert.match(err.message, /diverged/);
                return true;
            },
        );

        // The advanced blob keeps signing (leaf 1), so the refusal above was
        // the stale blob and not a stuck key.
        const second = pqhs.signStateful(suite, first.nextSecretKey, journal, MSG2, CTX);
        assert.equal(journal.nextLeaf(), 2);
        assert.equal(pqhs.verify(suite, publicKey, MSG2, CTX, second.signature), true);
    });

    check(`${suite}: a journal that is not the key's is refused before any spend`, () => {
        const { secretKey } = pqhs.keygenStatefulFromSeed(suite, seed(0x80 + i), 4);
        // A fresh journal, never adopted for this key: it honestly reports
        // leaf 0, exactly as the key's own unspent journal would, which is why
        // only the identity binding can tell them apart.
        const stranger = new MemoryLeafJournal();
        assert.throws(
            () => pqhs.signStateful(suite, secretKey, stranger, MSG, CTX),
            (err) => {
                assert.match(err.message, /does not belong to this key/);
                return true;
            },
        );
        assert.equal(stranger.nextLeaf(), 0, "the refusal must land before any commit");
    });

    check(`${suite}: the one-time leaf budget exhausts and fails closed`, () => {
        // Two leaves, spent in order, then the third attempt is refused.
        const { secretKey, publicKey } = pqhs.keygenStatefulFromSeed(suite, seed(0x90 + i), 2);
        const journal = new MemoryLeafJournal();
        pqhs.adoptKey(journal, pqhs.keyIdentity(suite, publicKey));

        let blob = secretKey;
        for (let n = 0; n < 2; n++) {
            const out = pqhs.signStateful(suite, blob, journal, MSG, CTX);
            assert.equal(pqhs.verify(suite, publicKey, MSG, CTX, out.signature), true);
            blob = out.nextSecretKey;
        }
        assert.equal(journal.nextLeaf(), 2);
        assert.throws(
            () => pqhs.signStateful(suite, blob, journal, MSG, CTX),
            (err) => {
                assert.match(err.message, /leaf budget is spent/);
                return true;
            },
        );
    });

    check(`${suite}: signStateless spends the few-time budget, not a leaf`, () => {
        const { secretKey, publicKey } = pqhs.keygenStatefulFromSeed(suite, seed(0xa0 + i), 4);
        const budget = new MemoryStatelessBudget();
        const sig = pqhs.signStateless(suite, secretKey, budget, MSG, CTX);
        assert.ok(sig.length <= pqhs.signatureLen(suite));
        // Plain `verify` accepts only the stateful path for H5/H6
        // (specification section 20.2): a stateless-path signature verifies
        // only through `verifyStateless`.
        assert.equal(pqhs.verify(suite, publicKey, MSG, CTX, sig), false);
        assert.equal(pqhs.verifyStateless(suite, publicKey, MSG, CTX, sig), true);
        assert.equal(pqhs.verifyStateful(suite, publicKey, MSG, CTX, sig), false);
    });
}

if (failures > 0) {
    console.error(`${failures} check(s) failed`);
    process.exit(1);
}
console.log("all checks passed");
