//! `hashsigs-rs` binds this value into the FORS message digest, so it is
//! part of what a stateless signature commits to. It is `keccak256` of the
//! profile's identity string, which is not the same string as
//! `<ShrincsScheme as PqStatefulScheme>::NAME`.
//!
//! Pinned here rather than read from `hashsigs-rs`, so that an upstream
//! change to the identity string or to the hash routine fails loudly
//! instead of silently matching itself. `hashsigs-rs` pins its own
//! `version_tag` the same way and for the same reason. Changing a value
//! below is a deliberate act: it means the wire format moved.

