//! Stateful (SHRINCS) suite test. Compiled only under a profile feature.
#![cfg(any(
    feature = "profile-256s",
    feature = "profile-256s-sha2",
    feature = "profile-128s-q18",
    feature = "profile-128s-q20"
))]
// Integration test binary: `cfg(test)` is always true here. `unwrap`/
// `expect`/`panic` are the normal way a test fails; the `hybrid_suite!`
// family of macros generates undocumented, unconditionally `pub` fixture
// structs, which is fine for a binary with no public API of its own.
#![cfg_attr(
    test,
    allow(
        clippy::unwrap_used,
        clippy::expect_used,
        clippy::panic,
        missing_docs,
        unreachable_pub
    )
)]
//! Leaf-indexed golden vectors for EdSh (ed25519 + SHRINCS) and SrSh (sr25519 +
//! SHRINCS): these pin the stateful wire format the way
//! `pqhybridsign/tests/golden.rs` pins the stateless EdMl44/SrMl44 format.
//!
//! A stateful signature's identity includes its leaf index: signing the
//! same message twice yields different bytes by design, because the leaf
//! advances between calls (`stateful_spec.rs`, test 32). So each vector here
//! is keyed on `(key state, message)`, not on message alone.
//!
//! # What these vectors prove, and what they do not
//!
//! Same caveat as the Cycle 1 vectors: generated by this implementation and
//! checked against this same implementation, so they catch a later change
//! that alters the wire format and nothing else.
//!
//! The stateful leaves (1, 2, 4) are reproduced live in this test:
//! `sign_stateful` is cheap, so re-signing exercises the encode path exactly
//! as the generator did. The stateless vector is not re-signed here --
//! `sign_stateless` grinds; in a debug build that costs 60 to 180 seconds
//! build -- so this test only re-verifies the recorded signature (the
//! decode and verify path) and checks that the two signature hexes the
//! generator captured over one message are equal, which is what "byte-
//! identical resign" means for a stateless call. The generator itself
//! asserted that equality live when the vector was produced (see
//! `generate_vectors_stateful.rs`); this test pins the result.
//!
//! Exactly one `profile-*` feature compiles per build (see `suites.rs`),
//! and every field in a vector is keyed on the profile that produced it.
//! Vectors exist only for `profile-256s`, so this file compiles only under
//! that feature. `check` still asserts the recorded `profile_name` against
//! the active one: if vectors for another profile are added later and the
//! gate below is widened, a mismatched pair fails loudly instead of
//! comparing signatures from two different parameter sets.
//!
//! Generating vectors for the other three profiles is real coverage that
//! this crate does not yet have. Measured cost of one stateless signature
//! in release: 1.16 s at `profile-256s`, 0.33 s at `profile-256s-sha2`,
//! 176.60 s at `profile-128s-q18`, 166.51 s at `profile-128s-q20`. Debug
//! builds run roughly 70 times slower, so generate in release.
#![cfg(feature = "profile-256s")]

use pqhybridsign::shrincs::{keygen, EdSh, PublicKey, ShrincsScheme, SrSh};
use pqhybridsign::stateful::{adopt_key, KeyIdentity, LeafJournal, StatefulHybridSignatureScheme};
use pqhybridsign::{component::PqStatefulScheme, suite::StatefulSuite};
use std::cell::RefCell;
use std::rc::Rc;

#[path = "profile_id/mod.rs"]
mod profile_id;

#[derive(Default, Clone)]
struct MemoryJournal {
    committed: Rc<RefCell<Vec<u32>>>,
    /// Which key this journal is the leaf record for, as durable here as
    /// the counter. A journal that has never been bound owns no key.
    bound: Rc<RefCell<Option<KeyIdentity>>>,
}

impl MemoryJournal {
    /// A journal already adopted by the key `identity` names: the one-off
    /// act an integrator performs when a key's durable journal is created.
    /// Signing refuses a journal that is not the key's.
    fn adopted(identity: KeyIdentity) -> Self {
        let mut journal = Self::default();
        adopt_key(&mut journal, identity).expect("adopt");
        journal
    }
}

impl LeafJournal for MemoryJournal {
    type Error = core::convert::Infallible;

    fn commit(&mut self, leaf: u32) -> Result<(), Self::Error> {
        self.committed.borrow_mut().push(leaf);
        Ok(())
    }

    fn next_leaf(&self) -> u32 {
        self.committed
            .borrow()
            .iter()
            .copied()
            .max()
            .map_or(0, |m| m + 1)
    }
    fn bound_key(&self) -> Option<KeyIdentity> {
        *self.bound.borrow()
    }

    fn bind_key(&mut self, key: KeyIdentity) -> Result<(), Self::Error> {
        *self.bound.borrow_mut() = Some(key);
        Ok(())
    }
}

#[derive(serde::Deserialize)]
struct StatefulVector {
    leaf_index: u32,
    msg_hex: String,
    signature_hex: String,
}

#[derive(serde::Deserialize)]
struct Vector {
    suite: String,
    label_hex: String,
    hkdf_info_includes_label_null_byte: bool,
    profile_name: String,
    profile_id_hex: String,
    max_signatures: u32,
    master_seed_hex: String,
    stored_public_key_hex: String,
    ctx_hex: String,
    filler_msg_hex: String,
    stateful_vectors: Vec<StatefulVector>,
    stateless_ctx_hex: String,
    stateless_msg_hex: String,
    stateless_signature_hex: String,
    stateless_resign_signature_hex: String,
}

fn check<S>(v: &Vector)
where
    S: StatefulSuite<Pq = ShrincsScheme>
        + StatefulHybridSignatureScheme<
            Signature = Vec<u8>,
            SecretKey = pqhybridsign::shrincs::SecretKey<S>,
            PublicKey = PublicKey<S>,
        >,
{
    assert_eq!(
        hex::encode(S::LABEL),
        v.label_hex,
        "{} label drifted",
        v.suite
    );
    let label = hex::decode(&v.label_hex).expect("label");
    assert_eq!(
        label.last(),
        Some(&0u8),
        "{} label must end in a null byte",
        v.suite
    );
    assert!(
        v.hkdf_info_includes_label_null_byte,
        "this crate pins the null byte inside info, same as Cycle 1"
    );
    assert_eq!(
        <S::Pq as PqStatefulScheme>::NAME,
        v.profile_name,
        "{} vector is keyed on the active profile",
        v.suite
    );
    assert_eq!(
        hex::encode(profile_id::PROFILE_ID),
        v.profile_id_hex,
        "{} vector was generated under a different hashsigs-rs profile identity; \
         the FORS digest binds this value, so the stateless signature below \
         cannot verify",
        v.suite
    );

    let master: [u8; 32] = hex::decode(&v.master_seed_hex)
        .expect("seed")
        .try_into()
        .expect("32 bytes");
    let (mut sk, pk) = keygen::<S>(&master, v.max_signatures).expect("keygen");

    // Stored form: classical public key || SHRINCS 32-byte commitment
    // (`StatefulSuite::STORED_PUBLIC_KEY_LEN` == 64), not the larger verify
    // form `PublicKey<S>::as_ref` returns.
    let commitment = &pk.pq_verify_key()[68..100];
    let mut stored_public_key = Vec::with_capacity(pk.classical().len() + 32);
    stored_public_key.extend_from_slice(pk.classical());
    stored_public_key.extend_from_slice(commitment);
    assert_eq!(
        hex::encode(&stored_public_key),
        v.stored_public_key_hex,
        "{} stored public key drifted",
        v.suite
    );

    reproduce_and_check_stateful_leaves::<S>(&mut sk, &pk, v);
    check_stateless_vector::<S>(&pk, v);
}

/// Re-sign leaves 1 through 4 in order (leaf 3 is a filler, not checked) and
/// compare the recorded leaves against the golden bytes.
fn reproduce_and_check_stateful_leaves<S>(sk: &mut S::SecretKey, pk: &PublicKey<S>, v: &Vector)
where
    S: StatefulSuite<Pq = ShrincsScheme>
        + StatefulHybridSignatureScheme<
            Signature = Vec<u8>,
            SecretKey = pqhybridsign::shrincs::SecretKey<S>,
            PublicKey = PublicKey<S>,
        >,
{
    let ctx = hex::decode(&v.ctx_hex).expect("ctx");
    let filler_msg = hex::decode(&v.filler_msg_hex).expect("filler msg");
    let mut journal = MemoryJournal::adopted(sk.key_identity());

    assert_eq!(
        v.stateful_vectors.len(),
        3,
        "{} must record leaves 1, 2 and a near-max leaf",
        v.suite
    );
    let by_leaf: std::collections::HashMap<u32, &StatefulVector> = v
        .stateful_vectors
        .iter()
        .map(|sv| (sv.leaf_index, sv))
        .collect();

    let max_leaf = by_leaf.keys().copied().max().expect("at least one vector");
    for leaf in 1..=max_leaf {
        if let Some(sv) = by_leaf.get(&leaf) {
            let msg = hex::decode(&sv.msg_hex).expect("msg");
            let sig = S::sign_stateful(sk, &mut journal, &msg, &ctx).expect("sign recorded leaf");
            assert_eq!(
                hex::encode(&sig),
                sv.signature_hex,
                "{} leaf {leaf} signature drifted",
                v.suite
            );
            assert!(S::verify_stateful(pk, &msg, &ctx, &sig));
        } else {
            // Unrecorded leaf: signed only to advance the state to the
            // next recorded leaf.
            S::sign_stateful(sk, &mut journal, &filler_msg, &ctx).expect("sign filler leaf");
        }
    }
}

fn check_stateless_vector<S>(pk: &PublicKey<S>, v: &Vector)
where
    S: StatefulSuite<Pq = ShrincsScheme>
        + StatefulHybridSignatureScheme<
            Signature = Vec<u8>,
            SecretKey = pqhybridsign::shrincs::SecretKey<S>,
            PublicKey = PublicKey<S>,
        >,
{
    assert_eq!(
        v.stateless_signature_hex, v.stateless_resign_signature_hex,
        "{} stateless resign must be byte-identical",
        v.suite
    );

    let stateless_ctx = hex::decode(&v.stateless_ctx_hex).expect("stateless ctx");
    let stateless_msg = hex::decode(&v.stateless_msg_hex).expect("stateless msg");
    let sig = hex::decode(&v.stateless_signature_hex).expect("stateless signature");
    assert!(
        S::verify_stateless(pk, &stateless_msg, &stateless_ctx, &sig),
        "{} stateless vector must verify",
        v.suite
    );
}

#[test]
fn h5_matches_the_golden_vector() {
    let v: Vector = serde_json::from_str(include_str!("vectors/h5.json")).expect("parse");
    assert_eq!(v.suite, "ED-SH");
    check::<EdSh>(&v);
}

#[test]
fn h6_matches_the_golden_vector() {
    let v: Vector = serde_json::from_str(include_str!("vectors/h6.json")).expect("parse");
    assert_eq!(v.suite, "SR-SH");
    check::<SrSh>(&v);
}
