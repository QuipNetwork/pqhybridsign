// Integration test binary: `cfg(test)` is always true here. `unwrap`/
// `expect`/`panic` are the normal way a test fails; the `hybrid_suite!`
// family of macros generates undocumented, unconditionally `pub` fixture
// structs, which is fine for a binary with no public API of its own.
#![cfg_attr(
    test,
    allow(
        clippy::unwrap_used,
        clippy::expect_used,
        clippy::panic,
        missing_docs,
        unreachable_pub
    )
)]
// Golden vectors: these pin the wire format. A change to the suite label,
// the `M'` message binding, the HKDF derivation or the signature layout
// breaks these tests instead of silently producing a new format.
//
// What these vectors prove, and what they do not:
//
// The vectors in tests/vectors/*.json were generated by this
// implementation, using tests/generate_vectors.rs, and they are checked
// against that same implementation. They therefore detect drift -- a later
// change that alters the wire format -- and nothing else. They cannot
// detect an error that was already present when they were generated. If
// the `M'` encoding, the HKDF `info` string or the empty fips204 `ctx` is
// wrong with respect to the specification, these vectors pin the mistake.
//
// There is no known-answer test here against RFC 8032, against FIPS 204,
// or against the specification's own vectors, and no cross-implementation
// vector shared with any other conforming implementation. The underlying
// component crates carry their own known-answer tests, so the primitives
// are covered; the composition layer this crate adds is not.
//
// Adding external or cross-implementation vectors is Cycle 2 work.
use pqhybridsign::composite::{keypair_from_seed, sign_deterministic, verify};
use pqhybridsign::{
    composite_delta,
    suite::{DeltaSuite, Suite},
};
use pqhybridsign::{EdFn512, EdMl44, SrFn512, SrMl44};

#[derive(serde::Deserialize)]
struct Vector {
    suite: String,
    label_hex: String,
    hkdf_info_includes_label_null_byte: bool,
    master_seed_hex: String,
    ctx_hex: String,
    msg_hex: String,
    nonce_hex: String,
    public_key_hex: String,
    signature_hex: String,
}

fn check<S: Suite>(v: &Vector) {
    let master: [u8; 32] = hex::decode(&v.master_seed_hex)
        .expect("seed")
        .try_into()
        .expect("32 bytes");
    let mut sk = vec![0u8; S::SECRET_KEY_LEN];
    let mut pk = vec![0u8; S::PUBLIC_KEY_LEN];
    keypair_from_seed::<S>(&master, &mut sk, &mut pk).expect("keygen");
    assert_eq!(
        hex::encode(&pk),
        v.public_key_hex,
        "{} public key drifted",
        v.suite
    );

    assert_eq!(
        hex::encode(S::LABEL),
        v.label_hex,
        "{} label drifted",
        v.suite
    );
    // The registry label is null terminated, and the terminator is part of
    // the bytes that go into `M'` and into the HKDF info string.
    let label = hex::decode(&v.label_hex).expect("label");
    assert_eq!(label.len(), 26, "{} label must be 26 bytes", v.suite);
    assert_eq!(
        label.last(),
        Some(&0u8),
        "{} label must end in a null byte",
        v.suite
    );
    // Specification section 9 is ambiguous about whether the null byte
    // belongs inside the HKDF info string. This crate pins the reading that
    // it does, which differs from the deployed quip-crypto-primitives.
    assert!(
        v.hkdf_info_includes_label_null_byte,
        "this crate pins the null byte inside info"
    );

    let ctx = hex::decode(&v.ctx_hex).expect("ctx");
    let msg = hex::decode(&v.msg_hex).expect("msg");
    let nonce = hex::decode(&v.nonce_hex).expect("nonce");
    let mut sig = vec![0u8; S::SIGNATURE_LEN];
    sign_deterministic::<S>(&sk, &msg, &ctx, &nonce, &mut sig).expect("sign");
    assert_eq!(
        hex::encode(&sig),
        v.signature_hex,
        "{} signature drifted",
        v.suite
    );
    assert!(verify::<S>(&pk, &msg, &ctx, &sig));
}

/// Same shape as [`check`], for a [`DeltaSuite`] (EdFn512, SrFn512): the label is
/// 28 bytes, not 26, and the signature length is not known ahead of
/// signing.
fn check_delta<S: DeltaSuite>(v: &Vector) {
    let master: [u8; 32] = hex::decode(&v.master_seed_hex)
        .expect("seed")
        .try_into()
        .expect("32 bytes");
    let mut sk = vec![0u8; S::SECRET_KEY_LEN];
    let mut pk = vec![0u8; S::PUBLIC_KEY_LEN];
    composite_delta::keypair_from_seed::<S>(&master, &mut sk, &mut pk).expect("keygen");
    assert_eq!(
        hex::encode(&pk),
        v.public_key_hex,
        "{} public key drifted",
        v.suite
    );

    assert_eq!(
        hex::encode(S::LABEL),
        v.label_hex,
        "{} label drifted",
        v.suite
    );
    let label = hex::decode(&v.label_hex).expect("label");
    assert_eq!(label.len(), 28, "{} label must be 28 bytes", v.suite);
    assert_eq!(
        label.last(),
        Some(&0u8),
        "{} label must end in a null byte",
        v.suite
    );
    assert!(
        v.hkdf_info_includes_label_null_byte,
        "this crate pins the null byte inside info"
    );

    let ctx = hex::decode(&v.ctx_hex).expect("ctx");
    let msg = hex::decode(&v.msg_hex).expect("msg");
    let nonce = hex::decode(&v.nonce_hex).expect("nonce");
    let mut sig = vec![0u8; S::MAX_SIGNATURE_LEN];
    let written =
        composite_delta::sign_deterministic::<S>(&sk, &msg, &ctx, &nonce, &mut sig).expect("sign");
    sig.truncate(written);
    assert_eq!(
        hex::encode(&sig),
        v.signature_hex,
        "{} signature drifted",
        v.suite
    );
    assert!(composite_delta::verify::<S>(&pk, &msg, &ctx, &sig));
}

#[test]
fn ed_ml44_matches_the_golden_vector() {
    let v: Vector = serde_json::from_str(include_str!("vectors/h1.json")).expect("parse");
    assert_eq!(v.suite, "ED-ML-44");
    check::<EdMl44>(&v);
}

#[test]
fn sr_ml44_matches_the_golden_vector() {
    let v: Vector = serde_json::from_str(include_str!("vectors/h3.json")).expect("parse");
    assert_eq!(v.suite, "SR-ML-44");
    check::<SrMl44>(&v);
}

#[test]
fn ed_fn512_matches_the_golden_vector() {
    let v: Vector = serde_json::from_str(include_str!("vectors/h2.json")).expect("parse");
    assert_eq!(v.suite, "ED-FN-512");
    check_delta::<EdFn512>(&v);
}

