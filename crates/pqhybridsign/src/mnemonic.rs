//! Chain-neutral BIP39 mnemonic phrase to master seed.
//!
//! # This is deliberately not standard BIP39
//!
//! Standard BIP39 runs PBKDF2-HMAC-SHA512 over the mnemonic **phrase text**
//! (salted with `"mnemonic" || password`). This module instead runs it over
//! the mnemonic's **entropy bytes**, exactly as Substrate's
//! `substrate_bip39::seed_from_entropy` does. That is not a bug: the whole
//! point of this module is to reproduce the master seed the chain and every
//! other Quip signer derive from the same phrase, and the chain runs the
//! Substrate variant. Do not "fix" this to hash the phrase text -- doing so
//! would silently derive a different key from every existing recovery
//! phrase.
//!
//! Byte parity with `quip-protocol-rs`'s `master_seed_from_mnemonic` (which
//! calls `substrate_bip39::seed_from_entropy`) is required, not just similar
//! behaviour: the golden-vector tests below were generated by running that
//! crate's own code and pin the result. This crate does not depend on
//! `substrate-bip39` itself -- the ten-line PBKDF2 call is inlined here so
//! this crate carries no Parity-branded dependency -- so those golden
//! vectors are what proves the two implementations still agree.

use crate::error::{Error, Result};
use alloc::string::String;
use bip39::{Language, Mnemonic};
use hmac::Hmac;
use pbkdf2::pbkdf2;
use sha2::Sha512;
use zeroize::Zeroize;

/// Length of the derived master seed, in bytes.
const MASTER_SEED_LEN: usize = 32;
/// Length of the raw PBKDF2-HMAC-SHA512 output, in bytes. The master seed is
/// the first half; the second half is discarded (and wiped, not just
/// dropped).
const PBKDF2_OUTPUT_LEN: usize = 64;
/// PBKDF2 round count. Fixed by the Substrate seed derivation this mirrors,
/// not a tunable: changing it would silently change every derived key.
const PBKDF2_ROUNDS: u32 = 2048;

/// Holds secret bytes so their wipe happens on drop.
///
/// Mirrors `classical::sr25519::Wiped`: a bare `zeroize()` call at the end of
/// a function stops covering an early return (`?`) the moment one is added
/// above it. Holding the value here makes the wipe structural instead: it
/// runs on every exit path, including a `?` propagated out of the PBKDF2
/// call below.
struct Wiped<T: Zeroize>(T);

impl<T: Zeroize> Drop for Wiped<T> {
    fn drop(&mut self) {
        self.0.zeroize();
    }
}

/// Derives the 32-byte chain-neutral master seed from an English BIP39
/// mnemonic phrase and an optional password.
///
/// This is Substrate's seed derivation, not standard BIP39 -- see the module
/// documentation. Concretely:
///
/// 1. Parse `phrase` as an English BIP39 mnemonic and take its entropy
///    bytes (`parse_in_normalized` rather than `parse_in`: English words are
///    lowercase ASCII, always already NFKD, so normalization is a no-op and
///    skipping it avoids pulling in `unicode-normalization`).
/// 2. Run PBKDF2-HMAC-SHA512 over the entropy (not the phrase text), salted
///    with `"mnemonic" || password`, for 2048 rounds, producing 64 bytes.
/// 3. Take the first 32 bytes as the master seed. Wipe the rest.
///
/// `password` defaults to the empty string when `None`, matching Substrate's
/// `Pair::from_phrase`.
///
/// # Errors
///
/// Returns [`Error::InvalidMnemonic`] if `phrase` is not a valid English
/// BIP39 mnemonic (wrong word count, an unknown word, or a bad checksum).
pub fn master_seed_from_mnemonic(
    phrase: &str,
    password: Option<&str>,
) -> Result<[u8; MASTER_SEED_LEN]> {
    let mnemonic = Mnemonic::parse_in_normalized(Language::English, phrase)
        .map_err(|_| Error::InvalidMnemonic)?;
    let (entropy_bytes, entropy_len) = mnemonic.to_entropy_array();
    let entropy = Wiped(entropy_bytes);

    let password = password.unwrap_or("");
    let mut salt = String::with_capacity(8 + password.len());
    salt.push_str("mnemonic");
    salt.push_str(password);
    let salt = Wiped(salt);

    let mut seed64 = Wiped([0u8; PBKDF2_OUTPUT_LEN]);
    pbkdf2::<Hmac<Sha512>>(
        &entropy.0[..entropy_len],
        salt.0.as_bytes(),
        PBKDF2_ROUNDS,
        &mut seed64.0,
    )
    .map_err(|_| Error::ComponentFailure)?;

    let mut master = [0u8; MASTER_SEED_LEN];
    master.copy_from_slice(&seed64.0[..MASTER_SEED_LEN]);
    Ok(master)
}

#[cfg(test)]
mod tests {
    use super::*;

    const PHRASE_12: &str = "bottom drive obey lake curtain smoke basket hold race lonely fit walk";
    const PHRASE_24: &str =
        "void come effort suffer camp survey warrior heavy shoot primary clutch \
                              crush open amazing screen patrol group space point ten exist slush \
                              involve unfold";

    fn hex(bytes: &[u8]) -> String {
        let mut out = String::with_capacity(bytes.len() * 2);
        for byte in bytes {
            out.push_str(&alloc::format!("{byte:02x}"));
        }
        out
    }

    // Golden vectors generated by calling `quip-protocol-rs`'s own
    // `master_seed_from_mnemonic` (crates/transaction-crypto-core/src/lib.rs,
    // on top of substrate-bip39 0.6.1) for these exact phrases, on
    // 2026-08-21. They pin byte-for-byte parity with the chain's own
    // derivation; a change to the salt construction, round count, or
    // entropy-vs-phrase choice would move these.
    #[test]
    fn twelve_word_phrase_matches_the_chain_integration() {
        let seed = master_seed_from_mnemonic(PHRASE_12, None).expect("valid phrase");
        assert_eq!(
            hex(&seed),
            "fac7959dbfe72f052e5a0c3c8d6530f202b02fd8f9f5ca3580ec8deb7797479e"
        );
    }

    #[test]
    fn twelve_word_phrase_with_password_matches_the_chain_integration() {
        let seed = master_seed_from_mnemonic(PHRASE_12, Some("hunter2")).expect("valid phrase");
        assert_eq!(
            hex(&seed),
            "87c2da7b75b1caac6e5f78b4c979ac67e1aec40ce0210453fd54046b56aa6810"
        );
    }

    #[test]
    fn twenty_four_word_phrase_matches_the_chain_integration() {
        let seed = master_seed_from_mnemonic(PHRASE_24, None).expect("valid phrase");
        assert_eq!(
            hex(&seed),
            "7316d66bc0ad15affde3eee7903fdbd893f5089961c9cd53144bc4b3f16e965b"
        );
    }

    #[test]
    fn password_changes_the_seed() {
        let no_password = master_seed_from_mnemonic(PHRASE_12, None).expect("valid phrase");
        let with_password =
            master_seed_from_mnemonic(PHRASE_12, Some("hunter2")).expect("valid phrase");
        assert_ne!(no_password, with_password);
    }

    #[test]
    fn derivation_is_deterministic() {
        let first = master_seed_from_mnemonic(PHRASE_12, None).expect("valid phrase");
        let second = master_seed_from_mnemonic(PHRASE_12, None).expect("valid phrase");
        assert_eq!(first, second);
    }

    #[test]
    fn invalid_phrase_is_rejected() {
        assert_eq!(
            master_seed_from_mnemonic("not a real mnemonic phrase at all", None),
            Err(Error::InvalidMnemonic)
        );
    }
}
